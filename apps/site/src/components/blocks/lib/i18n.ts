const STRINGS: Record<string, Strings> = { en, ur };

export type BlockStrings = Strings;

export function strings(locale: string): Strings {
  return STRINGS[locale] ?? en;
}

/** Badge text for a feature status; null for live (no badge). */
export function statusBadge(status: FeatureStatus | null | undefined, locale: string): string | null {
  if (!status || status === 'live') return null;
  return strings(locale).status[status];
}

/** Display name of an entry type ("Product", "Guide") in the page's language. */
export function typeLabel(type: CmsEntryType, locale: string): string {
  return locale === 'ur' ? UR_TYPE_LABELS[type] : ENTRY_TYPE_META[type].label;
}
