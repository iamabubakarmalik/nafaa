/**
 * Builds the two static SVG files the header uses (run from apps/site):
 *
 *   node src/components/layout/header/build-sprite.mjs
 *
 * - public/menu/icons.svg: one <symbol> per CMS icon (ALLOWED_ICONS, from
 *   src/lib/og/icon-nodes.ts), drawn the same way as CmsIcon (shapes joined
 *   into one path, tiny circles kept as dots). Menu links reference it with
 *   <use href="/menu/icons.svg?v=N#name">, so the page HTML carries only the
 *   icon name and the browser fetches and caches the sprite once.
 * - public/menu/logo.svg: the horizontal logo as one symbol whose fills read
 *   CSS custom properties (--nl-bowl, --nl-dot, --nl-word, set in theme.css),
 *   so the same file follows the light and dark themes.
 *
 * Run it again after ALLOWED_ICONS or the logo changes, then bump SPRITE_VERSION
 * in header/assets.ts so browsers fetch the new file.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(HERE, '../../../..');
const OUT = path.join(SITE, 'public/menu');

function read(rel) {
  return fs.readFileSync(path.join(SITE, rel), 'utf8');
}

// ─── Icons ───

const nodesSource = read('src/lib/og/icon-nodes.ts');
const body = nodesSource.slice(nodesSource.indexOf('= {') + 2, nodesSource.lastIndexOf('}') + 1);
const ICON_NODES = JSON.parse(body.replace(/,\s*}$/, '}'));

const NUM = String.raw`[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?`;
const LEADING_RELATIVE_MOVE = new RegExp(String.raw`^\s*m\s*(${NUM})\s*,?\s*(${NUM})\s*,?\s*`);

function absoluteStart(d) {
  const m = LEADING_RELATIVE_MOVE.exec(d);
  if (!m) return d;
  const rest = d.slice(m[0].length);
  return `M${m[1]} ${m[2]}${/^[-+.\d]/.test(rest) ? `l${rest}` : rest}`;
}

const num = (a, k) => Number(a[k] ?? 0);

function shapeToPath(tag, a) {
  switch (tag) {
    case 'path':
      return absoluteStart(a.d ?? '');
    case 'circle':
    case 'ellipse': {
      const cx = num(a, 'cx');
      const cy = num(a, 'cy');
      const rx = tag === 'circle' ? num(a, 'r') : num(a, 'rx');
      const ry = tag === 'circle' ? rx : num(a, 'ry');
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`;
    }
    case 'line':
      return `M${num(a, 'x1')} ${num(a, 'y1')}L${num(a, 'x2')} ${num(a, 'y2')}`;
    case 'polyline':
      return `M${a.points ?? ''}`;
    case 'polygon':
      return `M${a.points ?? ''}z`;
    case 'rect': {
      const x = num(a, 'x');
      const y = num(a, 'y');
      const w = num(a, 'width');
      const h = num(a, 'height');
      const rx = Math.min(w / 2, a.rx !== undefined ? num(a, 'rx') : num(a, 'ry'));
      const ry = Math.min(h / 2, a.ry !== undefined ? num(a, 'ry') : rx);
      if (!rx || !ry) return `M${x} ${y}h${w}v${h}h${-w}z`;
      const iw = w - 2 * rx;
      const ih = h - 2 * ry;
      return `M${x + rx} ${y}h${iw}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${ih}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-iw}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-ih}a${rx} ${ry} 0 0 1 ${rx} ${-ry}z`;
    }
    default:
      return '';
  }
}

const symbols = Object.entries(ICON_NODES).map(([name, nodes]) => {
  const parts = [];
  const dots = [];
  for (const [tag, attrs] of nodes) {
    if (tag === 'circle' && num(attrs, 'r') < 1) dots.push(`<circle cx="${attrs.cx}" cy="${attrs.cy}" r="${attrs.r}"/>`);
    else parts.push(shapeToPath(tag, attrs));
  }
  return `<symbol id="${name}" viewBox="0 0 24 24"><path d="${parts.join('')}"/>${dots.join('')}</symbol>`;
});

const icons =
  '<svg xmlns="http://www.w3.org/2000/svg">' +
  '<!-- Nafaa site icons: lucide 1.59 shapes (ISC licence). Generated by build-sprite.mjs; do not edit. -->' +
  symbols.join('') +
  '</svg>\n';

// ─── Logo ───

const logoSource = read('src/lib/brand/logo.ts');
const constant = (name) => {
  const m = new RegExp(`export const ${name} =\\s*'([^']+)'`).exec(logoSource);
  if (!m) throw new Error(`logo.ts: ${name} not found`);
  return m[1];
};
const lockup = /LOGO_LOCKUP = \{([\s\S]*?)\}/.exec(logoSource)?.[1] ?? '';
const field = (key) => new RegExp(`${key}:\\s*'?([^',\\n]+)'?`).exec(lockup)?.[1];

const logo =
  '<svg xmlns="http://www.w3.org/2000/svg">' +
  '<!-- Nafaa logo (brand/logo). Generated by build-sprite.mjs; do not edit. -->' +
  `<symbol id="l" viewBox="0 0 ${field('width')} ${field('height')}">` +
  `<g transform="${field('markTransform')}"><path style="fill:var(--nl-bowl,#16a34a)" d="${constant('LOGO_BOWL')}"/>` +
  `<path style="fill:var(--nl-dot,#f59e0b)" d="${constant('LOGO_DOT')}"/></g>` +
  `<path style="fill:var(--nl-word,#052e16)" transform="${field('wordTransform')}" d="${constant('LOGO_WORDMARK')}"/>` +
  '</symbol></svg>\n';

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'icons.svg'), icons);
fs.writeFileSync(path.join(OUT, 'logo.svg'), logo);
console.log(`icons.svg: ${symbols.length} icons, ${icons.length} bytes; logo.svg: ${logo.length} bytes`);
