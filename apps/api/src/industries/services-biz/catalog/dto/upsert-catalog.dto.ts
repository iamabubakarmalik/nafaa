import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { ServiceBusinessType, ServiceCategory, ServiceChargeType, TechnicianLevel, WarrantyType } from '@prisma/client';
import { IsArray, IsBoolean, IsEnum, IsInt, IsNumber, IsOptional, IsString, IsUUID, Max, MaxLength, Min } from 'class-validator';

export class UpsertCatalogDto {
  @ApiProperty() @IsString() @MaxLength(120) name!: string;
  @ApiPropertyOptional() @IsOptional() @IsString() code?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() description?: string;
  @ApiPropertyOptional({ enum: ServiceCategory }) @IsOptional() @IsEnum(ServiceCategory) category?: ServiceCategory;
  @ApiPropertyOptional({ enum: ServiceBusinessType }) @IsOptional() @IsEnum(ServiceBusinessType) businessType?: ServiceBusinessType;
  @ApiPropertyOptional({ enum: ServiceChargeType }) @IsOptional() @IsEnum(ServiceChargeType) chargeType?: ServiceChargeType;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100_000_000) baseCharge?: number;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100_000_000) hourlyRate?: number;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100_000_000) visitCharge?: number;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100_000_000) minCharge?: number;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100_000_000) maxCharge?: number;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100_000_000) emergencyCharge?: number;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100_000_000) weekendCharge?: number;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100_000_000) nightCharge?: number;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100_000_000) outOfCityCharge?: number;
  @ApiPropertyOptional() @IsOptional() @IsInt() @Min(0) @Max(100_000) estimatedDurationMin?: number;
  @ApiPropertyOptional() @IsOptional() @IsInt() @Min(0) @Max(100_000) minDurationMin?: number;
  @ApiPropertyOptional() @IsOptional() @IsInt() @Min(0) @Max(100_000) maxDurationMin?: number;
  @ApiPropertyOptional({ enum: TechnicianLevel }) @IsOptional() @IsEnum(TechnicianLevel) requiredSkillLevel?: TechnicianLevel;
  @ApiPropertyOptional({ type: [String] }) @IsOptional() @IsArray() @IsString({ each: true }) requiredTools?: string[];
  @ApiPropertyOptional({ type: [String] }) @IsOptional() @IsArray() @IsString({ each: true }) requiredParts?: string[];
  @ApiPropertyOptional() @IsOptional() @IsBoolean() requiresLicense?: boolean;
  @ApiPropertyOptional() @IsOptional() @IsString() licenseType?: string;
  @ApiPropertyOptional() @IsOptional() @IsInt() @Min(0) @Max(100_000) warrantyDays?: number;
  @ApiPropertyOptional({ enum: WarrantyType }) @IsOptional() @IsEnum(WarrantyType) warrantyType?: WarrantyType;
  @ApiPropertyOptional() @IsOptional() @IsString() warrantyTerms?: string;
  @ApiPropertyOptional() @IsOptional() @IsBoolean() isEmergency?: boolean;
  @ApiPropertyOptional() @IsOptional() @IsBoolean() isRemoteAvailable?: boolean;
  @ApiPropertyOptional() @IsOptional() @IsBoolean() requiresQuote?: boolean;
  @ApiPropertyOptional() @IsOptional() @IsBoolean() requiresAdvance?: boolean;
  @ApiPropertyOptional() @IsOptional() @IsNumber() @Min(0) @Max(100) advancePct?: number;
  @ApiPropertyOptional() @IsOptional() @IsString() imageUrl?: string;
  @ApiPropertyOptional({ type: [String] }) @IsOptional() @IsArray() @IsString({ each: true }) imageUrls?: string[];
  @ApiPropertyOptional() @IsOptional() @IsString() videoUrl?: string;
  @ApiPropertyOptional() @IsOptional() @IsInt() @Min(0) @Max(100_000) displayOrder?: number;
  @ApiPropertyOptional() @IsOptional() @IsBoolean() isPopular?: boolean;
  @ApiPropertyOptional() @IsOptional() @IsBoolean() isFeatured?: boolean;
  @ApiPropertyOptional() @IsOptional() @IsBoolean() isActive?: boolean;
  @ApiPropertyOptional() @IsOptional() @IsUUID() shopId?: string;
}
