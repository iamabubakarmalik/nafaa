const DICT: Record<Lang, Record<MessageKey, string>> = { en, ur };

export function t(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  // A `<key>_one` message, when present, is used for a count of exactly 1.
  const one = vars?.n === 1 ? (`${key}_one` as MessageKey) : null;
  let s = (one && (DICT[lang]?.[one] ?? en[one])) || (DICT[lang]?.[key] ?? en[key] ?? key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export type Translator = (key: MessageKey, vars?: Record<string, string | number>) => string;

export const translator = (lang: Lang): Translator => (key, vars) => t(lang, key, vars);
