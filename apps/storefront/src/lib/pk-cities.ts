/** Shown first in the picker. */
export const TOP_CITIES = ['Karachi', 'Lahore', 'Islamabad', 'Rawalpindi', 'Faisalabad', 'Multan', 'Peshawar', 'Quetta', 'Hyderabad', 'Gujranwala', 'Sialkot'];

const norm = (s: string) => s.toLowerCase().replace(/[^a-z]/g, '');

/** Cities matching what the shopper typed, best matches first. */
export function searchCities(query: string, limit = 8): Array<{ name: string; province: Province }> {
  const q = norm(query);
  if (!q) return TOP_CITIES.map((name) => ({ name, province: CITIES.find((c) => c[0] === name)?.[1] ?? 'PB' }));
  const starts: Array<{ name: string; province: Province }> = [];
  const contains: Array<{ name: string; province: Province }> = [];
  for (const [name, province, aliases] of CITIES) {
    const keys = [name, ...aliases.split('|').filter(Boolean)].map(norm);
    if (keys.some((k) => k.startsWith(q))) starts.push({ name, province });
    else if (keys.some((k) => k.includes(q))) contains.push({ name, province });
  }
  return [...starts, ...contains].slice(0, limit);
}

export function provinceOf(city: string): Province | null {
  return CITIES.find((c) => c[0] === city)?.[1] ?? null;
}
